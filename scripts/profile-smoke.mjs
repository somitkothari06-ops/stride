import assert from "node:assert/strict";
const base = process.env.STRIDE_BASE_URL || "http://127.0.0.1:3000";
const response = await fetch(`${base}/api/workspace?fresh=1`);
const cookie = response.headers.get("set-cookie").split(";")[0];
const initial = (await response.json()).state;
assert.equal(initial.sample, false);
assert.equal(initial.works.length, 0);
assert.equal(initial.profile.goal, "");
const context = { story: "Synthetic student who likes small projects and is still exploring.", experience: "Made one small calculator.", interests: "Databases and art", ambitions: "", constraints: "A long commute on class days", learningPreferences: "Short worked examples", direction: "exploring" };
const payload = { action: "aboutYou", name: "Synthetic profile check", year: "3rd year", minutes: 20, goal: "", context };
const saved = await fetch(`${base}/api/action`, { method: "POST", headers: { Cookie: cookie, Origin: base, "Content-Type": "application/json" }, body: JSON.stringify(payload) });
assert.equal(saved.status, 200, await saved.clone().text());
const reload = await fetch(`${base}/api/workspace`, { headers: { Cookie: cookie } }).then((r) => r.json());
assert.equal(reload.state.profile.lifeContext.direction, "exploring");
assert.equal(reload.state.profile.lifeContext.story, context.story);
assert.equal(reload.state.profile.onboardingComplete, true);
assert.equal(reload.state.works.length, 0);
const other = await fetch(`${base}/api/workspace?fresh=1`).then((r) => r.json());
assert.equal(other.state.profile.lifeContext, undefined);
const cleared = await fetch(`${base}/api/action`, { method: "POST", headers: { Cookie: cookie, Origin: base, "Content-Type": "application/json" }, body: JSON.stringify({ ...payload, context: { ...context, story: "", experience: "", interests: "", constraints: "", learningPreferences: "" } }) });
assert.equal(cleared.status, 200);
assert.equal((await cleared.json()).state.profile.lifeContext.story, "");
console.log("Profile HTTP check passed: fresh empty workspace, optional goal, story persistence, cross-session isolation and editable/clearable context.");
